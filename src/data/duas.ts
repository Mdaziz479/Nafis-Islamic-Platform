export const DUA_CATEGORIES = [...new Set(DUAS.flatMap(({ categories }) => categories))].sort((left, right) => left.localeCompare(right));

export function getDailyDua(date = new Date()) {
  const day = Math.floor(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()) / 86_400_000);
  const dua = DUAS[day % DUAS.length];
  return {
    title: dua.title,
    arabic: dua.arabic,
    translation: dua.meaning,
    source: dua.source,
  };
}